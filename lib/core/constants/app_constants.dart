// 파일 역할: 앱 전역에서 재사용되는 상수 모음
//
// 왜 별도 파일?
//   - 매직 넘버(반경 500m, 예산 15,000원 등)를 코드 곳곳에 인라인하면
//     "왜 이 값인지" 의도가 흩어지고 변경 시 누락 위험이 큼.
//   - 카테고리·문구 같은 도메인 정규화는 normalizer.dart에 두고,
//     "기본값/매직 넘버"는 이 파일에 한곳에 모아두는 정책.
//
// 추가 기준:
//   - 한 화면에서만 쓰는 값은 그 파일 내 const 로 유지(여기엔 넣지 않음).
//   - 2개 이상 화면에서 공유될 가능성이 보이면 이 파일로 승격.
//
// 디자인 토큰(색/간격/라운드)은 lib/core/theme 에 있으므로 여기엔 두지 않음.
// ══════════════════════════════════════════════════════════

/// 점심 세션 생성(CU-09) 화면에서 사용하는 기본값 모음.
///
/// 의미:
///   - radiusMeters: 호스트 GPS 기준 식당 검색 반경(미터). 도보 6~7분 거리.
///   - budgetPerPersonWon: 1인당 예산(원). 강남/판교 평균 점심값 기준 1.5만원.
///   - returnMinutes: 식사 후 사무실 복귀까지 여유 시간(분). 메뉴별 픽업/대기 포함.
///
/// 사용처: lib/features/session/session_create_screen.dart
class SessionDefaults {
  /// 식당 검색 반경 기본값(미터).
  /// 도보 약 6~7분 거리 — 점심시간 왕복 가능한 합리적 상한.
  static const int radiusMeters = 500;

  /// 1인당 예산 기본값(원).
  /// 강남/판교 사무실가 평균 점심값(2024~2026)에서 산정.
  static const int budgetPerPersonWon = 15000;

  /// 복귀 여유 시간 기본값(분).
  /// 식사 후 결제·이동 포함 30분이면 1시간 점심에 여유 30분.
  static const int returnMinutes = 30;
}
